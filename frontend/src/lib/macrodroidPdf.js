// Client-side PDF Generator for MoneyMap MacroDroid Setup Guide
import { jsPDF } from 'jspdf';

/**
 * Generates and downloads a personalized MacroDroid setup guide PDF
 * containing the user's personal Webhook URL and exact step-by-step instructions.
 */
export function downloadMacroDroidGuidePdf(webhookUrl, userName = 'User') {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 16;
  const maxWidth = pageWidth - margin * 2;
  let y = 18;

  const ensureSpace = (needed = 18) => {
    if (y + needed > 280) {
      doc.addPage();
      y = 18;
    }
  };

  // Header Banner
  doc.setFillColor(37, 99, 235); // Blue 600
  doc.roundedRect(margin, y, maxWidth, 26, 3, 3, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('MoneyMap - Android Auto-Sync Setup Guide', margin + 6, y + 11);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(`Prepared for: ${userName}  |  Zero-Burden Real-Time SMS & UPI Expense Tracking`, margin + 6, y + 19);
  y += 34;

  // Personal Webhook URL Box
  doc.setFillColor(240, 253, 244); // Emerald 50
  doc.setDrawColor(16, 185, 129); // Emerald 500
  doc.roundedRect(margin, y, maxWidth, 24, 2, 2, 'FD');
  doc.setTextColor(6, 95, 70);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('YOUR PERSONAL WEBHOOK URL (KEEP SECRET - COPY THIS):', margin + 4, y + 7);
  doc.setFont('courier', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(17, 24, 39);
  const urlLines = doc.splitTextToSize(webhookUrl || 'Open MoneyMap Settings to generate URL', maxWidth - 8);
  doc.text(urlLines, margin + 4, y + 14);
  y += 32;

  const addStep = (stepNum, title, bullets) => {
    ensureSpace(26);
    // Step pill
    doc.setFillColor(239, 246, 255);
    doc.roundedRect(margin, y, maxWidth, 8, 1.5, 1.5, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(30, 64, 175);
    doc.text(`Step ${stepNum}: ${title}`, margin + 3, y + 5.6);
    y += 12;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(55, 65, 81);
    for (const b of bullets) {
      const lines = doc.splitTextToSize(`• ${b}`, maxWidth - 4);
      ensureSpace(lines.length * 5 + 3);
      doc.text(lines, margin + 3, y);
      y += lines.length * 5 + 1.5;
    }
    y += 3;
  };

  addStep(1, 'Install & Enable MacroDroid (Free)', [
    'Install "MacroDroid - Device Automation" by ArloSoft from Google Play Store.',
    'Open the app, grant SMS permission when asked, and tap "Add Macro".',
    'Name the macro "MoneyMap Sync" at the top.',
  ]);

  addStep(2, 'Set the SMS Trigger (Red Box)', [
    'Tap "+" on the red Triggers box -> Call/SMS -> SMS Received.',
    'Select "Any Number" (or Any Contact).',
    'Under Text Content, choose "Any" -> tap OK. (MoneyMap automatically ignores OTPs and credits.)',
  ]);

  addStep(3, 'Add Offline Wait Block (Blue Box - Recommended)', [
    'Tap "+" on the blue Actions box -> Conditions / Loops -> If clause.',
    'Tap "+" on Conditions -> Connectivity -> Mobile Data On/Off -> Mobile Data Off -> OK.',
    'Tap "+" on Conditions again (AND) -> Connectivity -> Wifi State -> Not Connected to Network -> OK, then tap OK on the If clause.',
    'Tap the new "If" block -> Add child action -> search "wait" -> Wait Until Trigger.',
    'Tap "+" on Triggers -> Connectivity -> Data Connectivity Change (Data Connected) AND Wifi State Change (Connected) -> OK.',
  ]);

  addStep(4, 'Add HTTP Request Action (Blue Box)', [
    'Tap "+" on the blue Actions box -> Web Interactions -> HTTP Request.',
    'Request Method: Change GET to POST.',
    'URL: Paste your Personal Webhook URL shown in the green box above.',
    'Content-Type: Set to "text/plain" (important so multi-line bank SMS never break).',
    'Request Body: Enter [sms_message] (or tap "..." and choose "Incoming SMS message") -> tap OK.',
  ]);

  addStep(5, 'Reorder & Save', [
    'Tap the up/down arrows icon on the blue Actions header.',
    'Drag "HTTP Request (POST)" to the bottom, BELOW "End If" (Order: If -> Wait Until Trigger -> End If -> HTTP Request).',
    'Tap the checkmark (Save) button at the bottom-right, then confirm the macro toggle is ON.',
  ]);

  addStep(6, 'Allow Background Activity (Important)', [
    'Open Phone Settings -> Apps -> MacroDroid -> Battery (or Power consumption control).',
    'Select "Allow background activity" (or "Unrestricted") so Android never stops MacroDroid.',
    'Test it anytime from MoneyMap -> Settings -> "Send Test SMS" or by making a UPI payment!',
  ]);

  // Footer
  ensureSpace(14);
  doc.setDrawColor(229, 231, 235);
  doc.line(margin, y, pageWidth - margin, y);
  y += 6;
  doc.setFontSize(8.5);
  doc.setTextColor(107, 114, 128);
  doc.text('Generated by MoneyMap  |  Your expenses sync directly to your private Cloud Firestore account.', margin, y);

  doc.save('MoneyMap-MacroDroid-Setup-Guide.pdf');
}

