// Client-side PDF Generator for MoneyMap iPhone Shortcuts Setup Guide
import { jsPDF } from 'jspdf';

/**
 * Generates and downloads a personalized iPhone (Apple Shortcuts) setup guide PDF
 * containing the user's personal Webhook URL and exact step-by-step instructions.
 */
export function downloadIosGuidePdf(webhookUrl, userName = 'User') {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 16;
  const maxWidth = pageWidth - margin * 2;
  let y = 18;

  const ensureSpace = (needed = 18) => {
    if (y + needed > 280) {
      doc.addPage();
      y = 18;
    }
  };

  // Header Banner
  doc.setFillColor(17, 24, 39); // Gray 900 (Apple style)
  doc.roundedRect(margin, y, maxWidth, 26, 3, 3, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('MoneyMap - iPhone Shortcuts Setup Guide', margin + 6, y + 11);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(`Prepared for: ${userName}  |  Zero-Burden Real-Time SMS & UPI Expense Tracking`, margin + 6, y + 19);
  y += 34;

  // Personal Webhook URL Box
  doc.setFillColor(240, 253, 244);
  doc.setDrawColor(16, 185, 129);
  doc.roundedRect(margin, y, maxWidth, 24, 2, 2, 'FD');
  doc.setTextColor(6, 95, 70);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text('YOUR PERSONAL WEBHOOK URL (KEEP SECRET - COPY THIS):', margin + 4, y + 7);
  doc.setFont('courier', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(17, 24, 39);
  const urlLines = doc.splitTextToSize(webhookUrl || 'Open MoneyMap Settings to generate URL', maxWidth - 8);
  doc.text(urlLines, margin + 4, y + 14);
  y += 32;

  const addStep = (stepNum, title, bullets) => {
    ensureSpace(26);
    doc.setFillColor(243, 244, 246);
    doc.roundedRect(margin, y, maxWidth, 8, 1.5, 1.5, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(17, 24, 39);
    doc.text(`Step ${stepNum}: ${title}`, margin + 3, y + 5.6);
    y += 12;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(55, 65, 81);
    for (const b of bullets) {
      const lines = doc.splitTextToSize(`• ${b}`, maxWidth - 4);
      ensureSpace(lines.length * 5 + 3);
      doc.text(lines, margin + 3, y);
      y += lines.length * 5 + 1.5;
    }
    y += 3;
  };

  addStep(1, 'Open Apple Shortcuts (Built-in App)', [
    'Open the built-in "Shortcuts" app on your iPhone (no third-party app download needed).',
    'Tap the "Automation" tab at the bottom, then tap "+" (or "New Automation") in the top-right.',
  ]);

  addStep(2, 'Set the Bank SMS Trigger', [
    'Scroll down and tap "Message".',
    'Under "Message Contains", type: debited  (Tip: create a second automation for "Dr" if your bank uses "Dr Rs..." like Union Bank).',
    'Select "Run Immediately" (important so it runs automatically without asking for confirmation).',
    'Tap "Next" -> tap "New Blank Automation".',
  ]);

  addStep(3, 'Add Webhook Action (Get Contents of URL)', [
    'Tap "Add Action" -> search for "Get Contents of URL" and select it.',
    'Tap the "URL" field and paste your Personal Webhook URL from the green box above.',
    'Tap the arrow (>) next to URL to expand options:',
    '  - Method: Change GET to POST.',
    '  - Request Body: Select JSON.',
    '  - Tap "Add new field" -> choose Text -> Key: text -> Value: tap "Shortcut Input".',
  ]);

  addStep(4, 'Save & Test', [
    'Tap "Done" in the top-right corner.',
    'Make a Rs. 1 UPI payment (or test from MoneyMap -> Settings -> "Send Test SMS").',
    'Your expense will appear automatically in MoneyMap within 2-3 seconds!',
  ]);

  // Footer
  ensureSpace(14);
  doc.setDrawColor(229, 231, 235);
  doc.line(margin, y, pageWidth - margin, y);
  y += 6;
  doc.setFontSize(8.5);
  doc.setTextColor(107, 114, 128);
  doc.text('Generated by MoneyMap  |  Your expenses sync directly to your private Cloud Firestore account.', margin, y);

  doc.save('MoneyMap-iPhone-Shortcuts-Setup-Guide.pdf');
}
